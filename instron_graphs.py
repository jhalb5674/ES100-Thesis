# Step 2: Get a list of all CSV files in the folder
csv_files = [f for f in os.listdir(folder_path) if f.endswith('.csv')]
sample_width = 0.015 # in m
sample_length = 0.119 # in m
# sample_thickness = 1.7 #in cm
