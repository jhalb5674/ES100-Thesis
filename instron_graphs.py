youngs_modulus_elastic_values = []
youngs_modulus_plastic_values = []
file_names = []
poissons = []

# Step 3: Loop through each file and load it, then plot displacement vs force
for file in csv_files:
  file_path = os.path.join(folder_path, file)

    # Load the CSV file into a pandas DataFrame
  df = pd.read_csv(file_path, skiprows = 6)

  # Ensure 'Force' and 'Displacement' columns are numeric (replace 'Force' and 'Displacement' with the actual column names if different)
  df['Force'] = pd.to_numeric(df['Force'], errors='coerce')  # Convert to numeric, setting non-convertible values to NaN
  df['Displacement'] = pd.to_numeric(df['Displacement'], errors='coerce')  # Convert to numeric, setting non-convertible values to NaN

  # Drop rows where 'Force' or 'Displacement' is NaN
  df.dropna(subset=['Force', 'Displacement'], inplace=True)

  # Calculate stress and strain
  df['Stress'] = (df['Force']*1000) / (sample_width * sample_thickness)  # Replace with actual width and thickness
  df['Strain'] = (df['Displacement']/1000) / sample_length  # Replace with actual initial length

  # Shift the stress and strain data to start at zero by subtracting the first value
  df['Stress'] = df['Stress'] - df['Stress'].iloc[0]  # Shift the Stress
  df['Strain'] = df['Strain'] - df['Strain'].iloc[0]  # Shift the Strain

  # Calculate Young's modulus in the elastic region
  elastic_region = df[df['Strain'] < 0.01]  # Modify threshold as needed
  slope_elastic, _, _, _, _ = linregress(elastic_region['Strain'], elastic_region['Stress'])
  youngs_modulus_elastic = slope_elastic
  youngs_modulus_elastic_values.append(youngs_modulus_elastic)

  # Estimate Young's modulus in the plastic region by selecting a higher strain range
  plastic_region = df[(df['Strain'] > 0.05) & (df['Strain'] < 0.1)]
  slope_plastic, _, _, _, _ = linregress(plastic_region['Strain'], plastic_region['Stress'])
  youngs_modulus_plastic = slope_plastic
  youngs_modulus_plastic_values.append(youngs_modulus_plastic)

# Plot with the label only added once for the color 'b'
  if not label_added["b"]:
    plt.plot(df['Strain'], (df['Stress']/1000000), color='b', label="10mm/min", linewidth = 1)
    label_added["b"] = True
  else:
    plt.plot(df['Strain'], (df['Stress']/1000000), color='b', linewidth = 1)

