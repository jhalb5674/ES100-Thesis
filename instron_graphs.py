def find_fracture_point(df):
    """
    Finds the fracture stress and strain point from a stress-strain curve.
    This accounts for cases where the yield stress is higher than the fracture stress
    by identifying a significant drop in stress after the fracture point.

    Parameters:
        dataframe (pd.DataFrame): DataFrame containing columns 'Strain' and 'Stress'.

    Returns:
        tuple: A tuple (fracture_strain, fracture_stress) representing the fracture point.
    """
    # Check if required columns are present
    if 'Strain' not in df.columns or 'Stress' not in df.columns:
        raise ValueError("The DataFrame must contain 'Strain' and 'Stress' columns.")

    # Ensure the DataFrame is sorted by strain (if not already sorted)
    df = df.sort_values(by='Strain').reset_index(drop=True)

    # Identify the maximum stress (could be yield stress)
    max_stress_idx = df['Stress'].idxmax()
    max_stress = df.loc[max_stress_idx, 'Stress']

    # Check for significant drop in stress after the maximum stress
    for i in range(max_stress_idx + 1, len(df)):
        if df.loc[i, 'Stress'] < 0.8 * max_stress:  # A 20% drop is considered significant
            fracture_stress = df.loc[i - 1, 'Stress']
            fracture_strain = df.loc[i - 1, 'Strain']
            return fracture_strain, fracture_stress

    # If no significant drop is found, assume fracture occurs at the maximum stress
    fracture_strain = df.loc[max_stress_idx, 'Strain']
    return fracture_strain, max_stress

